import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const galleryDir = path.join(__dirname, 'public', 'images', 'art-gallery');
if (!fs.existsSync(galleryDir)) {
  fs.mkdirSync(galleryDir, { recursive: true });
}

const sourceDirs = [
  path.join(__dirname, 'images'),
  path.join(__dirname, 'img')
];

const validExts = ['.jpg', '.jpeg', '.png', '.webp'];

// 1. Check all source directories for new images
for (const sDir of sourceDirs) {
  if (fs.existsSync(sDir)) {
    const files = fs.readdirSync(sDir).sort();
    for (const f of files) {
      const lower = f.toLowerCase();
      if (validExts.some(ext => lower.endsWith(ext)) || lower.endsWith('.jpg.jpeg')) {
        const srcPath = path.join(sDir, f);
        // Normalize filename
        let targetName = f;
        if (targetName.endsWith('.jpg.jpeg')) {
          targetName = targetName.replace('.jpg.jpeg', '.jpg');
        }
        const targetPath = path.join(galleryDir, targetName);
        if (!fs.existsSync(targetPath)) {
          fs.copyFileSync(srcPath, targetPath);
          console.log(`[Auto-Sync] Added new image: ${targetName}`);
        }
      }
    }
  }
}

// 2. Read all files in public/images/art-gallery
const allGalleryFiles = fs.readdirSync(galleryDir)
  .filter(f => validExts.some(ext => f.toLowerCase().endsWith(ext)))
  .sort();

// 3. Generate src/data/artGalleryData.js
const galleryItems = allGalleryFiles.map((file, idx) => {
  const num = String(idx + 1).padStart(2, '0');
  return {
    id: `art-${num}`,
    number: num,
    title: `Artwork ${num}`,
    image: `/images/art-gallery/${file}`
  };
});

const content = `// Automatically generated by sync-gallery.js — DO NOT EDIT DIRECTLY
export const artGalleryItems = ${JSON.stringify(galleryItems, null, 2)};
`;

const dataPath = path.join(__dirname, 'src', 'data', 'artGalleryData.js');
fs.writeFileSync(dataPath, content, 'utf-8');

console.log(`[Auto-Sync] Art Gallery synchronized with ${galleryItems.length} artworks.`);
